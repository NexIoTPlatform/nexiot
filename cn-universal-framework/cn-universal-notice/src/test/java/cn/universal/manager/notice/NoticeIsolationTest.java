/** Exercises actual generated SQL against a database, not just mocked filtering. */
class NoticeIsolationTest {
  private SqlSession session;
  private NoticeChannelServiceImpl channels;
  private NoticeTemplateServiceImpl templates;
  private NoticeRecordServiceImpl records;
  private NoticeAccess access;
  private IoTUser actor;
  private IoTUserService users;
  private DeptDataPermissionScope scope;

  @BeforeEach void setup() throws Exception {
    var dataSource = new UnpooledDataSource("org.h2.Driver", "jdbc:h2:mem:" + System.nanoTime() + ";MODE=PostgreSQL", "sa", "");
    var configuration = new Configuration(new Environment("test", new JdbcTransactionFactory(), dataSource));
    var helper = new MapperHelper();
    helper.registerMapper(tk.mybatis.mapper.common.Mapper.class);
    for (Class<?> mapper : List.of(NoticeChannelMapper.class, NoticeTemplateMapper.class, NoticeSendRecordMapper.class, WechatOpenIdBindingMapper.class)) configuration.addMapper(mapper);
    helper.processConfiguration(configuration);
    session = new SqlSessionFactoryBuilder().build(configuration).openSession(true);
    sql("CREATE TABLE iot_user (union_id VARCHAR PRIMARY KEY, tenant_id VARCHAR, dept_id BIGINT)");
    sql("INSERT INTO iot_user VALUES ('me','tenant-a',10), ('peer','tenant-a',10), ('other-dept','tenant-a',20), ('other-tenant','tenant-b',10)");
    sql("CREATE TABLE notice_channel(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id VARCHAR, dept_id BIGINT, name VARCHAR, channel_type VARCHAR, config VARCHAR, status VARCHAR, remark VARCHAR, creator VARCHAR, create_time TIMESTAMP, update_time TIMESTAMP)");
    sql("CREATE TABLE notice_template(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id VARCHAR, dept_id BIGINT, name VARCHAR, channel_type VARCHAR, channel_id BIGINT, wechat_config VARCHAR, content VARCHAR, receivers VARCHAR, status VARCHAR, remark VARCHAR, creator VARCHAR, create_time TIMESTAMP, update_time TIMESTAMP)");
    sql("CREATE TABLE notice_send_record(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id VARCHAR, dept_id BIGINT, template_id BIGINT, config_id BIGINT, channel_type VARCHAR, receivers VARCHAR, params VARCHAR, status VARCHAR, result VARCHAR, send_time TIMESTAMP, creator VARCHAR)");
    sql("CREATE TABLE notice_wechat_openid(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id VARCHAR, dept_id BIGINT, app_id VARCHAR, channel_id BIGINT, user_key VARCHAR, openid VARCHAR, unionid VARCHAR, status VARCHAR, create_time TIMESTAMP, update_time TIMESTAMP, UNIQUE(app_id,openid), UNIQUE(app_id,user_key))");
    for (int i=1;i<=4;i++) {
      String owner = List.of("me","peer","other-dept","other-tenant").get(i-1);
      String tenant = i==4 ? "tenant-b" : "tenant-a";
      int dept = i==3 ? 20 : 10;
      sql("INSERT INTO notice_channel(id,tenant_id,dept_id,name,channel_type,status,creator,config) VALUES ("+i+",'"+tenant+"',"+dept+",'channel-"+i+"','email','0','"+owner+"','{}')");
      sql("INSERT INTO notice_template(id,tenant_id,dept_id,name,channel_type,channel_id,status,creator,content) VALUES ("+i+",'"+tenant+"',"+dept+",'template-"+i+"','email',"+i+",'1','"+owner+"','hello')");
    }
    actor = new IoTUser(); actor.setUnionId("me"); actor.setTenantId("tenant-a"); actor.setDeptId(10L);
    users = mock(IoTUserService.class);
    when(users.selectUserByUnionId("me")).thenReturn(actor);
    scope = new DeptDataPermissionScope();
    ReflectionTestUtils.setField(scope,"tenantId","tenant-a");
    ReflectionTestUtils.setField(scope,"currentUnionId","me");
    ReflectionTestUtils.setField(scope,"scopeDeptIds",Set.of(10L));
    ReflectionTestUtils.setField(scope,"scopeUnionIds",Set.of("me","peer"));
    DeptDataPermissionSupport departments = spy(new DeptDataPermissionSupport());
    doReturn(scope).when(departments).resolveScope("me");
    access = new NoticeAccess(users, mock(OauthClientDetailsMapper.class), departments);
    SecurityContextHolder.getContext().setAuthentication(new JwtAuthenticationToken(Jwt.withTokenValue("test").header("alg","RS256").subject("me").build(), List.of()));
    channels = new NoticeChannelServiceImpl();
    ReflectionTestUtils.setField(channels,"noticeChannelMapper",session.getMapper(NoticeChannelMapper.class));
    ReflectionTestUtils.setField(channels,"access",access);
    ReflectionTestUtils.setField(channels,"templates",session.getMapper(NoticeTemplateMapper.class));
    ReflectionTestUtils.setField(channels,"bindings",session.getMapper(WechatOpenIdBindingMapper.class));
    templates = new NoticeTemplateServiceImpl(session.getMapper(NoticeTemplateMapper.class),channels,mock(NoticeService.class));
    ReflectionTestUtils.setField(templates,"access",access);
    records = new NoticeRecordServiceImpl(session.getMapper(NoticeSendRecordMapper.class));
    ReflectionTestUtils.setField(records,"access",access);
  }
  private void sql(String sql) throws Exception { try(var statement=session.getConnection().createStatement()) { statement.execute(sql); } }
  @AfterEach void close() { SecurityContextHolder.clearContext(); if(session!=null) session.close(); }

  @Test void sqlScopesListsAndDetailsToTenantAndDepartment() {
    assertEquals(List.of(1L,2L), channels.list().stream().map(NoticeChannel::getId).sorted().toList());
    assertEquals(2,templates.list().size());
    assertNotNull(channels.getById(2L));
    assertThrows(ResponseStatusException.class,()->channels.getById(3L));
    assertThrows(ResponseStatusException.class,()->channels.getById(4L));
    assertThrows(ResponseStatusException.class,()->templates.getById(4L));
  }
  @Test void tenantAdminSeesAllDepartmentsButNeverOtherTenant() {
    ReflectionTestUtils.setField(scope,"tenantAdmin",true);
    assertEquals(3,channels.list().size());
    assertNotNull(channels.getById(3L));
    assertThrows(ResponseStatusException.class,()->channels.getById(4L));
  }
  @Test void missingAndDisabledIdentityCannotListOrMutate() {
    actor.setStatus(1);
    assertThrows(ResponseStatusException.class,channels::list);
    actor.setStatus(0); SecurityContextHolder.clearContext();
    assertThrows(ResponseStatusException.class,channels::list);
    assertThrows(ResponseStatusException.class,()->templates.deleteBatch(List.of(1L)));
  }
  @Test void mixedBatchFailsBeforeAnyChange() {
    assertThrows(ResponseStatusException.class,()->templates.disableBatch(List.of(1L,4L)));
    assertEquals("1",templates.getById(1L).getStatus());
    assertThrows(ResponseStatusException.class,()->templates.deleteBatch(List.of(1L,3L)));
    assertNotNull(templates.getById(1L));
    assertThrows(IllegalArgumentException.class,()->channels.deleteBatch(List.of(1L)));
    templates.disableBatch(List.of(1L,2L));
    assertEquals("0",templates.getById(2L).getStatus());
  }
  @Test void ownershipCannotBeForgedOrTransferredDuringSave() {
    NoticeChannel channel = new NoticeChannel();
    org.springframework.beans.BeanUtils.copyProperties(channels.getById(1L), channel);
    channel.setTenantId("tenant-b"); channel.setDeptId(20L); channel.setCreator("other-tenant");
    channels.save(channel);
    assertEquals("tenant-a",channels.getById(1L).getTenantId());
    assertEquals(10L,channels.getById(1L).getDeptId());
    assertEquals("me",channels.getById(1L).getCreator());
    NoticeTemplate template=templates.getById(1L); template.setChannelId(4L);
    assertThrows(ResponseStatusException.class,()->templates.save(template));
  }
  @Test void legacyOwnershipFallbackDoesNotExposeOtherTenants() throws Exception {
    sql("UPDATE notice_channel SET tenant_id=NULL, dept_id=NULL");
    IoTUser peer=new IoTUser();peer.setUnionId("peer");peer.setTenantId("tenant-a");peer.setDeptId(10L);
    when(users.selectUserByUnionId("peer")).thenReturn(peer);
    assertEquals(2,channels.list().size());
    assertEquals("tenant-a",channels.getById(2L).getTenantId());
  }
  @Test void recordTypeFilterUsesChannelTypeAndPreservesTenantScope() throws Exception {
    sql("INSERT INTO notice_send_record(id,tenant_id,dept_id,channel_type,status,creator) VALUES (1,'tenant-a',10,'email','SUCCESS','me'),(2,'tenant-b',10,'email','SUCCESS','other-tenant'),(3,'tenant-a',10,'wechat','SUCCESS','me')");
    assertEquals(List.of(1L), records.search(null,"email","SUCCESS").stream().map(NoticeSendRecord::getId).toList());
  }
  @Test void appIdAndOpenIdIdentityIsUniqueAcrossChannels() throws Exception {
    sql("INSERT INTO notice_wechat_openid(app_id,openid,user_key) VALUES ('wx-a','same-openid','one')");
    assertThrows(java.sql.SQLException.class,()->sql("INSERT INTO notice_wechat_openid(app_id,openid,user_key) VALUES ('wx-a','same-openid','two')"));
    sql("INSERT INTO notice_wechat_openid(app_id,openid,user_key) VALUES ('wx-b','same-openid','two')");
  }
  private WechatOpenIdService openIds() {
    WechatOpenIdService service = new WechatOpenIdService();
    ReflectionTestUtils.setField(service,"bindingMapper",session.getMapper(WechatOpenIdBindingMapper.class));
    ReflectionTestUtils.setField(service,"channels",channels);
    ReflectionTestUtils.setField(service,"access",access);
    return service;
  }

  @Test void bindingsShareAppIdentityButRespectOriginDepartmentAndTenant() throws Exception {
    sql("UPDATE notice_channel SET channel_type='wechat', config='{\"appId\":\"wx-a\"}'");
    var bindings = openIds();
    assertEquals("employee", bindings.bind(1L,"employee","openid-1"));
    assertEquals("openid-1",bindings.resolve(2L,"employee"));
    assertEquals("employee",bindings.bind(2L,"scan_again","openid-1"));
    assertThrows(IllegalArgumentException.class,()->bindings.bind(2L,"different","openid-1"));
    assertThrows(IllegalArgumentException.class,()->bindings.bind(1L,"employee","openid-2"));
    sql("INSERT INTO notice_wechat_openid(app_id,openid,user_key,tenant_id,dept_id,channel_id,status) VALUES ('wx-a','dept-user','hidden','tenant-a',20,3,'1')");
    assertThrows(ResponseStatusException.class,()->bindings.resolve(1L,"hidden"));
    actor.setTenantId("tenant-b");
    ReflectionTestUtils.setField(scope,"tenantId","tenant-b");
    ReflectionTestUtils.setField(scope,"tenantAdmin",true);
    assertNull(bindings.resolve(4L,"employee"));
    assertThrows(RuntimeException.class,()->bindings.bind(4L,"other-tenant","openid-1"));
    assertNull(bindings.resolve(4L,"other-tenant"));
  }

  @Test void sendingIgnoresForgedAuditCreatorAndChecksChannelBeforeExternalCall() throws Exception {
    var sender = mock(cn.universal.manager.notice.service.channel.NoticeSendChannel.class);
    when(sender.support("email")).thenReturn(true);
    when(sender.send(anyString(),anyString(),any(),any())).thenReturn(cn.universal.manager.notice.service.channel.NoticeSendResult.builder().success(true).build());
    var service = new NoticeServiceImpl(session.getMapper(NoticeTemplateMapper.class),records,channels,List.of(sender));
    ReflectionTestUtils.setField(service,"access",access);
    NoticeSendRequest request = new NoticeSendRequest(); request.setTemplateId(1L);request.setCreator("other-tenant");request.setReceivers("test@example.invalid");request.setParams(java.util.Map.of());
    assertTrue(service.sendR(request).isSuccess());
    var saved=records.list().get(0);
    assertEquals("me",saved.getCreator());assertEquals("tenant-a",saved.getTenantId());assertEquals(10L,saved.getDeptId());
    clearInvocations(sender);
    sql("UPDATE notice_template SET channel_id=4 WHERE id=1");session.clearCache();
    assertFalse(service.sendR(request).isSuccess());
    verifyNoInteractions(sender);
  }

  @Test void trustedBackgroundActorIsScopedAndAlwaysCleared() {
    SecurityContextHolder.clearContext();
    assertEquals(2, access.runAs("me",channels::list).size());
    assertNull(access.currentUser());
    assertThrows(ResponseStatusException.class, () -> access.runAs("me", () -> channels.getById(4L)));
    assertNull(access.currentUser());
  }

}
