  @Test
  void exportUsesCompleteProductEntityAndIncludesSharedNetworkGatewayAndHistory() {
    IoTProduct gateway =
        IoTProduct.builder()
            .productKey("gw")
            .tenantId("tenant")
            .creatorId("operator")
            .name("网关")
            .deviceNode("GATEWAY")
            .build();
    IoTProduct sub =
        IoTProduct.builder()
            .productKey("sub")
            .tenantId("tenant")
            .creatorId("operator")
            .name("子设备")
            .gwProductKey("gw")
            .tags("工业,测试")
            .deviceNode("GATEWAY_SUB_DEVICE")
            .networkUnionId("source-net")
            .productSecret("secret")
            .thirdConfiguration("{\"customField\":[]}")
            .configuration("{\"industrial\":{\"protocol\":\"MODBUS\"}}")
            .metadata("{\"properties\":[]}")
            .build();
    when(productMapper.selectAllDevProductV2List(any()))
        .thenReturn(List.of(IoTProductExportVO.builder().productKey("sub").build()));
    when(productMapper.selectOne(any()))
        .thenAnswer(
            invocation ->
                "sub".equals(((IoTProduct) invocation.getArgument(0)).getProductKey())
                    ? sub
                    : gateway);
    when(networkMapper.selectByExample(any()))
        .thenReturn(
            List.of(
                Network.builder()
                    .unionId("source-net")
                    .tenantId("tenant")
                    .type("MQTT_SERVER")
                    .state(1)
                    .configuration("{}")
                    .build()));
    when(versions.selectVersionListByProductKey(any()))
        .thenReturn(
            List.of(
                IoTProductMetadataVersion.builder()
                    .version(1)
                    .metadataSnapshot(sub.getMetadata())
                    .build()));
    List<ProductExportPackageDTO> exported = service.exportProductPackages(new IoTProductQuery());
    assertEquals(2, exported.size());
    ProductExportPackageDTO dto = exported.getFirst();
    assertEquals("2.0", dto.getExportVersion());
    assertEquals("gw", dto.getProduct().getGwProductKey());
    assertEquals("工业,测试", dto.getProduct().getTags());
    assertEquals("secret", dto.getProduct().getProductSecret());
    assertEquals("source-net", dto.getNetworks().getFirst().getUnionId());
    assertTrue(dto.getNetworks().getFirst().getState());
    assertEquals(1, dto.getMetadataVersions().size());
    var decoded = JSONUtil.toList(JSONUtil.toJsonStr(exported), ProductExportPackageDTO.class);
    assertEquals("gw", decoded.getFirst().getProduct().getGwProductKey());
    assertEquals("source-net", decoded.getFirst().getNetworks().getFirst().getUnionId());
  }
