  @Test
  void rawMetadataReplacesCompletelyRetainsExtensionsAndRejectsInvalidReplacement() {
    IoTProduct target =
        IoTProduct.builder()
            .id(7L)
            .tenantId("tenant")
            .creatorId("operator")
            .productKey("target")
            .metadata(
                "{\"properties\":[{\"id\":\"old\",\"name\":\"原有\"}],\"events\":[],\"functions\":[],\"version\":\"v1\"}")
            .build();
    when(productMapper.selectOne(any())).thenReturn(target);
    String incoming =
        "{\"properties\":[{\"id\":\"new\",\"name\":\"新增\",\"custom\":{\"unit\":\"kPa\"}}],\"events\":[],\"functions\":[],\"description\":\"完整模型\"}";
    service.batchUpdateMetadata(
        IoTProductMetadataBatchBO.builder()
            .productKey("target")
            .mode("replace")
            .metadata(incoming)
            .build());
    assertEquals(1, JSONUtil.parseObj(target.getMetadata()).getJSONArray("properties").size());
    assertTrue(target.getMetadata().contains("custom"));
    assertFalse(target.getMetadata().contains("v1"));
    assertTrue(target.getMetadata().contains("完整模型"));
    verify(action).metadataCreate("target");
    String before = target.getMetadata();
    assertThrows(
        IoTException.class,
        () ->
            service.batchUpdateMetadata(
                IoTProductMetadataBatchBO.builder()
                    .productKey("target")
                    .mode("replace")
                    .metadata("{\"properties\":false}")
                    .build()));
    assertEquals(before, target.getMetadata());
    for (String invalid : List.of("", " ")) {
      assertThrows(
          IoTException.class,
          () ->
              service.batchUpdateMetadata(
                  IoTProductMetadataBatchBO.builder()
                      .productKey("target")
                      .mode("replace")
                      .metadata(invalid)
                      .build()));
      assertEquals(before, target.getMetadata());
    }
    assertThrows(
        IoTException.class,
        () ->
            service.batchUpdateMetadata(
                IoTProductMetadataBatchBO.builder()
                    .productKey("target")
                    .mode("merge")
                    .metadata(incoming)
                    .build()));
    verify(productMapper, times(1)).updateByPrimaryKeySelective(any());
  }

