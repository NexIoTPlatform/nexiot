  @Test
  void successPreservesIndustrialConfigMapsGatewayAndSharedNetworkUsesSessionTenant() {
    var a = product("a");
    a.getProduct().setDeviceNode("GATEWAY_SUB_DEVICE");
    a.getProduct().setGwProductKey("b");
    var b = product("b");
    b.getProduct().setDeviceNode("GATEWAY");
    a.setNetwork(network());
    b.setNetwork(network());
    a.getProduct().setNetworkUnionId("source-net");
    a.getProduct().setThirdDownRequest("{\"networkUnionId\":\"source-net\"}");
    b.getProduct().setNetworkUnionId("source-net");
    a.setProtocol(protocol());
    a.getProtocol().setConfiguration("{\"provider\":\"a\",\"networkUnionId\":\"source-net\"}");
    var result = service.importProductPackages(List.of(a, b), "operator", "tenant");
    assertEquals(2, count("products"));
    assertEquals(1, count("protocols"));
    assertEquals(1, count("networks"));
    assertEquals(inserted.get(1).getProductKey(), inserted.get(0).getGwProductKey());
    assertEquals("new-network-1", inserted.get(0).getNetworkUnionId());
    assertTrue(inserted.get(0).getThirdDownRequest().contains("new-network-1"));
    verify(protocolMapper)
        .updateByPrimaryKeySelective(argThat(p -> p.getConfiguration().contains("new-network-1")));
    assertEquals("new-network-1", inserted.get(1).getNetworkUnionId());
    assertTrue(inserted.get(0).getConfiguration().contains("activeCollection"));
    assertTrue(inserted.get(0).getConfiguration().contains("defaultPort"));
    assertEquals("tenant", insertedNetworks.getFirst().getTenantId());
    assertFalse(insertedNetworks.getFirst().isStateEnabled());
    verify(action, times(2)).create(any(), eq("operator"));
    assertEquals(2, result.getProductCount());
    assertEquals(1, result.getProtocolCount());
    assertEquals(1, result.getNetworkCount());
  }

