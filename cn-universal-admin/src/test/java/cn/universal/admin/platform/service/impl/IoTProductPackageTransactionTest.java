  @Test
  void lateProtocolFailureRollsBackEveryProductAndSuppressesEvents() {
    var a = product("a");
    a.setProtocol(protocol());
    var b = product("b");
    b.setProtocol(protocol());
    doAnswer(
            invocation -> {
              IoTDeviceProtocol p = invocation.getArgument(0);
              if (count("protocols") > 0) throw new IllegalStateException("第二个协议失败");
              return jdbc.update("INSERT INTO protocols VALUES (?,?)", p.getId(), p.getTenantId());
            })
        .when(protocolMapper)
        .insertDevProtocol(any());
    IoTException e =
        assertThrows(
            IoTException.class,
            () -> service.importProductPackages(List.of(a, b), "operator", "tenant"));
    assertTrue(e.getMessage().contains("第2个产品"));
    assertTrue(e.getMessage().contains("第二个协议失败"));
    assertEquals(0, count("products"));
    assertEquals(0, count("protocols"));
    verifyNoInteractions(action);
  }

