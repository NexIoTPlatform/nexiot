CREATE TABLE `iot_algorithm_config` (
                                        `id` bigint NOT NULL AUTO_INCREMENT COMMENT '主键ID',
                                        `product_id` bigint DEFAULT NULL,
                                        `product_key` varchar(64) NOT NULL COMMENT '产品Key',
                                        `algorithm_type` varchar(50) NOT NULL COMMENT '算法类型',
                                        `algorithm_name` varchar(100) DEFAULT NULL COMMENT '算法名称',
                                        `description` varchar(500) DEFAULT NULL COMMENT '算法描述',
                                        `enable` tinyint(1) DEFAULT '1' COMMENT '是否启用：1-启用, 0-禁用',
                                        `config_json` text COMMENT '算法配置JSON',
                                        `execution_mode` varchar(20) DEFAULT 'LOCAL' COMMENT '执行模式：LOCAL-本地, REMOTE-远程, AUTO-自动',
                                        `service_url` varchar(255) DEFAULT NULL COMMENT '远程服务地址',
                                        `timeout` int DEFAULT '5000' COMMENT '超时时间(ms)',
                                        `create_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
                                        `update_time` datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
                                        `creator_id` varchar(64) DEFAULT NULL COMMENT '创建人',
                                        PRIMARY KEY (`id`),
                                        KEY `idx_product_id` (`product_id`),
                                        KEY `idx_product_key` (`product_key`),
                                        KEY `idx_algorithm_type` (`algorithm_type`),
                                        KEY `idx_enable` (`enable`)
) ENGINE=InnoDB AUTO_INCREMENT=17 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='算法配置表';

CREATE TABLE `iot_algorithm_result` (
                                        `id` bigint NOT NULL AUTO_INCREMENT COMMENT '主键ID',
                                        `device_id` varchar(64) NOT NULL COMMENT '设备ID',
                                        `product_key` varchar(64) NOT NULL COMMENT '产品Key',
                                        `algorithm_type` varchar(50) NOT NULL COMMENT '算法类型',
                                        `algorithm_name` varchar(100) DEFAULT NULL COMMENT '算法名称',
                                        `result_json` text COMMENT '结果JSON（完整结果数据）',
                                        `health_score` decimal(5,2) DEFAULT NULL COMMENT '健康分数（0-100）',
                                        `health_level` varchar(20) DEFAULT NULL COMMENT '健康等级：HEALTHY-健康, GOOD-良好, WARNING-预警, ABNORMAL-异常',
                                        `is_anomaly` tinyint(1) DEFAULT NULL COMMENT '是否异常：1-异常, 0-正常',
                                        `anomaly_score` decimal(10,4) DEFAULT NULL COMMENT '异常分数',
                                        `success` tinyint(1) DEFAULT '1' COMMENT '是否成功：1-成功, 0-失败',
                                        `error_message` varchar(500) DEFAULT NULL COMMENT '错误信息',
                                        `create_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
                                        PRIMARY KEY (`id`),
                                        KEY `idx_device_time` (`device_id`,`create_time`),
                                        KEY `idx_product_time` (`product_key`,`create_time`),
                                        KEY `idx_algorithm_type` (`algorithm_type`),
                                        KEY `idx_is_anomaly` (`is_anomaly`),
                                        KEY `idx_create_time` (`create_time`)
) ENGINE=InnoDB AUTO_INCREMENT=73 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='算法结果表';

CREATE TABLE `iot_algorithm_alert_record` (
                                              `id` bigint NOT NULL AUTO_INCREMENT COMMENT '主键ID',
                                              `device_id` varchar(64) NOT NULL COMMENT '设备ID',
                                              `product_key` varchar(64) NOT NULL COMMENT '产品Key',
                                              `algorithm_type` varchar(50) NOT NULL COMMENT '算法类型',
                                              `alert_type` varchar(50) NOT NULL COMMENT '告警类型：ANOMALY/HEALTH/THRESHOLD/TREND',
                                              `alert_level` varchar(20) NOT NULL COMMENT '告警级别：CRITICAL/HIGH/MEDIUM/LOW',
                                              `alert_score` decimal(10,4) DEFAULT NULL COMMENT '告警分数',
                                              `alert_title` varchar(200) DEFAULT NULL COMMENT '告警标题',
                                              `alert_message` text COMMENT '告警消息',
                                              `suggestions` text COMMENT '处理建议',
                                              `status` varchar(20) DEFAULT 'OPEN' COMMENT '状态：OPEN/ACKNOWLEDGED/RESOLVED/SUPPRESSED',
                                              `acknowledged_time` datetime DEFAULT NULL COMMENT '确认时间',
                                              `acknowledged_by` varchar(64) DEFAULT NULL COMMENT '确认人',
                                              `resolved_time` datetime DEFAULT NULL COMMENT '解决时间',
                                              `resolved_by` varchar(64) DEFAULT NULL COMMENT '解决人',
                                              `execution_id` varchar(64) DEFAULT NULL COMMENT '关联的执行ID',
                                              `parent_alert_id` bigint DEFAULT NULL COMMENT '父告警ID（用于告警聚合）',
                                              `create_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
                                              `update_time` datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
                                              PRIMARY KEY (`id`),
                                              KEY `idx_device_time` (`device_id`,`create_time`),
                                              KEY `idx_algorithm_type` (`algorithm_type`),
                                              KEY `idx_status` (`status`),
                                              KEY `idx_alert_level` (`alert_level`,`create_time`),
                                              KEY `idx_execution_id` (`execution_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='算法告警记录表';